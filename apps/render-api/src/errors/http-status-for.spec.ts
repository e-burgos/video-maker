describe('httpStatusFor', () => {
  it.each(RENDER_API_ERROR_CODES.map((code) => ({ code, status: EXPECTED_STATUS_BY_CODE[code] })))(
    'maps $code to HTTP $status',
    ({ code, status }) => {
      expect(httpStatusFor(code)).toBe(status);
    },
  );
});
