  ROUTE_NOT_FOUND: 404,
  METHOD_NOT_ALLOWED: 405,
  SERVER_CONFIG_INVALID: 500,
  INTERNAL_ERROR: 500,
  PROJECT_NOT_FOUND: 404,
  PROJECT_SLUG_INVALID: 422,
  PROJECT_ALREADY_EXISTS: 409,
  PROJECT_LAYOUT_INVALID: 500,
  ASSET_ROLE_INVALID: 422,
  ASSET_PATH_INVALID: 422,
  ASSET_ALREADY_EXISTS: 409,
  ASSET_CONTENT_LENGTH_REQUIRED: 411,
